'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const context={window:{}};
vm.createContext(context);
vm.runInContext(fs.readFileSync('js/characters/campaign-training.js','utf8'),context);
const api=context.window.IronCrownCampaignTraining;
const state={camped:false,target:null,supplies:4,minutes:1410,day:3};
let active=[{id:'char-mara'},{id:'char-iven'}],battleActive=false,nextResult={ok:true,eventId:'event-1',results:[]};
const calls=[];
const service=api.create({getState:()=>state,party:{active:()=>active},loyalty:{record:(type,ids)=>{calls.push({type,ids:ids.slice()});return nextResult}},isBattleActive:()=>battleActive});
const snapshot=()=>({camped:state.camped,target:state.target,supplies:state.supplies,minutes:state.minutes,day:state.day});
assert.equal(service.availability().ok,false,'training requires an established camp');
assert.match(service.availability().reason,/Establish camp/);
assert.equal(service.train().ok,false);
assert.equal(calls.length,0);
state.camped=true;state.target='kingsbridge';
assert.match(service.availability().reason,/travelling/);assert.equal(service.train().ok,false);
state.target=null;battleActive=true;
assert.match(service.availability().reason,/during battle/);assert.equal(service.train().ok,false);
battleActive=false;active=[];
assert.match(service.availability().reason,/at least one named companion/);assert.equal(service.train().ok,false);
active=[{id:'char-mara'},{id:'char-iven'}];state.supplies=1;
assert.match(service.availability().reason,/2 supplies/);assert.equal(service.train().ok,false);
assert.equal(calls.length,0,'eligibility failures do not emit events');
state.supplies=4;nextResult={ok:false,reason:'Unknown participant'};
const beforeFailure=snapshot();
assert.equal(service.train().ok,false);
assert.deepEqual(snapshot(),beforeFailure,'failed loyalty application does not consume time or supplies');
assert.equal(calls.length,1);
nextResult={ok:true,eventId:'event-1',results:[]};
const available=service.availability();assert.equal(available.ok,true);
assert.deepEqual(available.participantIds,['char-mara','char-iven']);
const result=service.train();assert.equal(result.ok,true);
assert.deepEqual(result.participantIds,['char-mara','char-iven']);
assert.deepEqual(calls[1],{type:'troops:training',ids:['char-mara','char-iven']},'only exact active named IDs receive training');
assert.equal(state.supplies,2);assert.equal(state.day,4);assert.equal(state.minutes,30);
const afterSuccess=snapshot();nextResult={ok:true,duplicate:true};
assert.equal(service.train().ok,false,'duplicate event cannot charge for training again');
assert.deepEqual(snapshot(),afterSuccess,'duplicate event does not consume campaign resources');
console.log('campaign camp-training rules passed');
