'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const html=fs.readFileSync('index.html','utf8');
const game=fs.readFileSync('js/game.js','utf8');
const state=fs.readFileSync('js/core/state.js','utf8');
const save=fs.readFileSync('js/core/save.js','utf8');
const shell=fs.readFileSync('sw.js','utf8');
assert.match(html,/id="payCompanions"/,'company panel exposes daily companion payment');
assert.match(html,/Pay 5 gold per active named companion once each campaign day/,'payment cost and cadence are disclosed');
assert.ok(html.indexOf('campaign-loyalty-runtime.js')<html.indexOf('campaign-payment.js'),'loyalty runtime loads before the payment service');
assert.ok(html.indexOf('campaign-payment.js')<html.indexOf('js/game.js'),'payment service loads before campaign integration');
assert.match(game,/function updatePaymentControl\(\)/);
assert.match(game,/function payCompanions\(\)/);
assert.match(game,/campaignPayment\.pay\(\)/);
assert.match(game,/\$\('payCompanions'\)\.onclick=payCompanions/);
assert.match(game,/campaignPayment=window\.IronCrownCampaignPayment\.create/);
assert.match(game,/updateTrainingControl\(\);updatePaymentControl\(\)/,'travel/camp controls refresh payment availability');
assert.match(game,/state\.target=selected\.id;updateCampControls\(\)/,'starting settlement travel disables camp, training and payment controls');
assert.match(game,/state\.target='__free__';updateCampControls\(\)/,'starting off-road travel disables camp, training and payment controls');
assert.match(game,/processEncounters\(currentPoint\(\)\.x,currentPoint\(\)\.y\);drawDiscoveries\(\);updateExplorationControls\(\);updateCampControls\(\)/,'arrival refreshes camp, training and payment availability');
assert.match(game,/function cancel\(\)\{[^}]*state\.target=null;[^}]*updateCampControls\(\)/,'cancelling travel refreshes camp, training and payment availability');
assert.match(state,/lastCompanionPayDay:0/,'new campaigns begin with no paid day');
assert.match(state,/saveVersion:11/,'campaign state advertises save version 11');
assert.match(save,/const SAVE_VERSION=options\.version\|\|11/);
assert.match(save,/lastCompanionPayDay:state\.lastCompanionPayDay/,'save persists the last paid day');
assert.match(save,/state\.lastCompanionPayDay=number\(d\.lastCompanionPayDay,0,0,999999\)/,'load validates the paid day');
assert.match(shell,/iron-crown-shell-v22/);
assert.match(shell,/\.\/js\/characters\/campaign-payment\.js/);
console.log('campaign daily companion payment UI and save contract passed');
