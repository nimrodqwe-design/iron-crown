const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const context={window:{}};
vm.runInNewContext(fs.readFileSync('js/characters/recruitment.js','utf8'),context);
const api=context.window.IronCrownRecruitment;
const candidate={id:'mara',name:'Mara of Greyhaven',role:'companion',background:'Former caravan guard',motivation:'loyalty',baseCost:100,trust:20};
let game=api.create({gold:500,reputation:20,candidates:[candidate]});
const wary=game.quote('mara');
assert.equal(wary.ok,true);
assert.ok(wary.cost>100,'low trust and poor reputation should increase the asking price');
game.updateTrust('mara',90);
game.updateReputation(85);
const trusted=game.quote('mara');
assert.equal(trusted.ok,true);
assert.equal(trusted.cost,0,'a highly trusted recruit may volunteer for a respected commander');
const joined=game.recruit('mara');
assert.equal(joined.recruited,true);
assert.equal(joined.cost,0);
assert.equal(game.quote('mara').ok,false,'a recruited candidate cannot be recruited twice');
const locked=api.create({gold:500,reputation:10,candidates:[{...candidate,id:'locked',requirements:{minimumReputation:40}}]});
assert.equal(locked.quote('locked').ok,false,'requirements must be enforced');
const poor=api.create({gold:0,reputation:50,candidates:[{...candidate,id:'paid',motivation:'coin',trust:50,baseCost:50}]});
assert.equal(poor.recruit('paid').reason,'Not enough gold');
assert.equal(poor.snapshot().recruited.length,0,'failed recruitment must not mutate roster');
const scalable=api.create({gold:10000,reputation:50,candidates:Array.from({length:150},(_,i)=>({...candidate,id:'recruit-'+i,role:i%3===0?'companion':'soldier'}))});
assert.equal(scalable.snapshot().candidates.length,150,'candidate roster has no arbitrary tiny hard cap');
console.log('Recruitment motivation tests passed.');
