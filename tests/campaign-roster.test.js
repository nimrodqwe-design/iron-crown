'use strict';
const fs=require('fs'),vm=require('vm'),assert=require('assert');
const context={window:{crypto:{randomUUID:()=> 'campaign-test'}}};vm.createContext(context);
vm.runInContext(fs.readFileSync('js/characters/campaign-roster.js','utf8'),context);
const api=context.window.IronCrownCharacters;
const roster=api.create({campaignId:'campaign-test'});
const a=roster.add({name:'Mara',role:'companion',motivation:'glory'});
const b=roster.add({name:'Iven',role:'officer'});
assert.strictEqual(a.id,'ic:campaign-test:character:1');
assert.strictEqual(b.id,'ic:campaign-test:character:2');
assert.strictEqual(roster.get(a.id).name,'Mara');
const event1=roster.createEventId();
assert.strictEqual(event1,'ic:campaign-test:event:1');
const saved=roster.snapshot();
assert.strictEqual(saved.version,2);
const restored=api.restore(saved);
assert.deepStrictEqual(JSON.parse(JSON.stringify(restored.snapshot())),JSON.parse(JSON.stringify(saved)));
assert.strictEqual(restored.add({name:'Sera'}).id,'ic:campaign-test:character:3');
assert.strictEqual(restored.createEventId(),'ic:campaign-test:event:2');
assert.throws(()=>api.create({campaignId:'campaign-test',characters:[a,a]}));
const warnings=[];
const legacy=api.restore({version:1,nextId:3,characters:[{id:'char-1',name:'Legacy Mara',role:'companion'}]},{campaignId:'legacy-campaign',onWarning:m=>warnings.push(m)});
assert.strictEqual(legacy.get('ic:legacy-campaign:character:1').name,'Legacy Mara');
assert.strictEqual(legacy.add({name:'Next'}).id,'ic:legacy-campaign:character:3');
const recovered=api.restore({version:2,campaignId:'campaign-test',nextCharacterSequence:1,nextEventSequence:1,characters:[{id:'wrong-id',name:'Bad'}]},{onWarning:m=>warnings.push(m)});
assert.strictEqual(recovered.list().length,0);
assert.ok(warnings.length>0);
console.log('campaign roster checks passed');