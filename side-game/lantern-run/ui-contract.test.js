'use strict';
const fs=require('fs'),vm=require('vm'),assert=require('assert');
const html=fs.readFileSync(__dirname+'/index.html','utf8');
assert.match(html,/id="levelName"/,'the current ruin name must have a visible heading');
assert.match(html,/api\.levelName\(state\.level\)/,'the UI must read the current ruin name from the state module');
assert.match(html,/levelName\.textContent!==selectedLevelName/,'the ruin heading updates only when progression changes levels');
assert.match(html,/role="grid"/,'board must expose grid semantics');
assert.match(html,/id="grid"[^>]*tabindex="0"/,'board itself must be keyboard focusable');
assert.match(html,/aria-keyshortcuts="ArrowUp ArrowDown ArrowLeft ArrowRight"/,'board must advertise arrow-key shortcuts');
assert.match(html,/\.grid:focus-visible/,'keyboard focus must remain visible');
assert.match(html,/<progress id="lightMeter" max="12" value="12"/,'remaining lantern light must have a visible progress meter');
assert.match(html,/aria-valuetext/,'light meter must expose a readable remaining-light value');
assert.match(html,/moveCount\.textContent='Moves: '\+state\.moves/,'HUD must expose the current move count');
assert.match(html,/id="hint" aria-describedby="status"/,'hint control must be labelled by the live status region');
assert.match(html,/api\.hint\(state\)/,'UI must use the state module for route hints');
assert.match(html,/api\.useHint\(state\)/,'hint usage must be tracked by the state module');
assert.match(html,/api\.score\(state\)/,'the UI must display the state module score');
assert.match(html,/window\.LanternRunProgress\.create\(window\.localStorage\)/,'personal records use the isolated progress store');
assert.match(html,/window\.LanternRunProgress\.create\(null\)/,'a throwing localStorage getter falls back to session-only records');
assert.match(html,/id="scoreValue"/);
assert.match(html,/id="bestScore"/);
assert.match(html,/id="hintCount"/);
assert.match(html,/progress\.record\(state\.level,score\)/,'successful escapes record a per-ruin best score');
assert.match(html,/does not consume lantern light/,'hint feedback must explain that it is free');
assert.match(html,/aria-rowcount="5"/);
assert.match(html,/aria-live="polite"/);
assert.match(html,/aria-current','location'/,'player position must be announced');
assert.match(html,/api\.cellKind\(x,y,state\.level\)/,'UI must use the current level for cell types');
assert.match(html,/api\.cellLabel\(x,y,state\.level\)/,'UI must use the current level for cell labels');
assert.doesNotMatch(html,/new Set\(\[['"]1,3/,'UI must not duplicate hazard coordinates');
assert.match(html,/button\.disabled=state\.ended/,'movement controls must disable after the run ends');
assert.match(html,/state\.ended&&state\.outcome==='escaped'/,'only a successful escape advances to the next ruin');
assert.match(html,/state\.outcome==='escaped'\?'Next ruin':'Try again'/,'the restart control communicates the correct next action');
assert.match(html,/Restart ruin/,'an active run can be restarted without advancing');
const inline=[...html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g)].map(match=>match[1]).filter(source=>source.trim());
assert.strictEqual(inline.length,1,'expected one inline UI script');
new vm.Script(inline[0]);
console.log('Lantern Run UI contract checks passed');