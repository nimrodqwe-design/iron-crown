'use strict';
const assert=require('node:assert/strict');
const Progress=require('./progress.js');
const values=new Map();
const storage={getItem:key=>values.has(key)?values.get(key):null,setItem:(key,value)=>values.set(key,String(value))};
const records=Progress.create(storage);
assert.equal(records.best(0),null);
const first=records.record(0,620);
assert.deepEqual(first,{ok:true,updated:true,best:620,persisted:true});
assert.equal(records.best(0),620);
assert.deepEqual(records.record(0,600),{ok:true,updated:false,best:620,persisted:true});
assert.equal(records.record(1,720).updated,true,'ruins keep independent records');
const restored=Progress.create(storage);
assert.equal(restored.best(0),620,'best scores survive a new progress-store instance');
assert.equal(restored.best(1),720);
assert.deepEqual(restored.snapshot(),{version:1,bestScores:[620,720,null]});
assert.equal(restored.record(3,500).ok,false,'invalid level indexes are rejected');
assert.equal(restored.record(0,-1).ok,false,'negative scores are rejected');
assert.equal(restored.record(0,10001).ok,false,'unbounded scores are rejected');
values.set(Progress.KEY,'not-json');
assert.equal(Progress.create(storage).best(0),null,'corrupt records fail closed');
const readFailure={getItem(){throw new Error('storage blocked')},setItem(){throw new Error('storage blocked')}};
const fallback=Progress.create(readFailure);
const result=fallback.record(2,510);
assert.equal(result.updated,true,'storage failure does not block the current session');
assert.equal(result.persisted,false);
assert.equal(fallback.best(2),510);
const memoryOnly=Progress.create(null);
assert.equal(memoryOnly.record(0,400).persisted,false,'missing storage uses session-only records');
const writeFailure={getItem(){return null},setItem(){throw new Error('quota exceeded')}};
const writeFallback=Progress.create(writeFailure);
const writeResult=writeFallback.record(1,455);
assert.equal(writeResult.updated,true,'a write failure still records the best score for this session');
assert.equal(writeResult.persisted,false,'a write failure is not reported as persistent');
assert.equal(writeFallback.best(1),455,'the session best remains available after a write failure');
console.log('Lantern Run progress checks passed');